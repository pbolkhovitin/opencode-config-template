#!/usr/bin/env python3
"""Generate a project OpenCode config from one or more profiles.

Profiles are additive only for MCP servers and agents: the project config is
merged on top of the profile chosen via ``ocp <profile>``. Model and permissions
still default to that base profile, but the project file may override them.
Agent prompt paths are rewritten to absolute paths so they resolve from any
project directory.

    oc-project-init.py --profiles dev,infra
    oc-project-init.py --profiles dev,infra --check
    oc-project-init.py --profiles dev,infra --dry-run

Source configs are read from ``$XDG_CONFIG_HOME/opencode-<profile>`` (or
``opencode`` for default) and fall back to the repository's ``profiles/``.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROFILES = ["default", "dev", "infra", "net", "sec", "ot", "mgnt", "design"]
MARKER = "Generated by oc-project-init.py"


def strip_jsonc(text: str) -> str:
    out: list[str] = []
    i = 0
    in_string = False
    escaped = False
    while i < len(text):
        char = text[i]
        if in_string:
            out.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            i += 1
            continue
        if char == '"':
            in_string = True
            out.append(char)
            i += 1
            continue
        if char == "/" and i + 1 < len(text) and text[i + 1] == "/":
            newline = text.find("\n", i)
            i = len(text) if newline < 0 else newline
            continue
        if char == "/" and i + 1 < len(text) and text[i + 1] == "*":
            end = text.find("*/", i + 2)
            i = len(text) if end < 0 else end + 2
            continue
        out.append(char)
        i += 1
    cleaned = "".join(out)
    return re.sub(r",\s*([}\]])", r"\1", cleaned)


def load_jsonc(path: Path) -> dict:
    return json.loads(strip_jsonc(path.read_text(encoding="utf-8")))


def config_home() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))


def resolve_profile(profile: str, home: Path) -> Path:
    candidates = []
    if profile == "default":
        candidates.append(home / "opencode" / "opencode.json")
        candidates.append(home / "opencode" / "opencode.jsonc")
    else:
        candidates.append(home / f"opencode-{profile}" / "opencode.json")
        candidates.append(home / f"opencode-{profile}" / "opencode.jsonc")
        candidates.append(ROOT / "profiles" / profile / "opencode.jsonc")
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise SystemExit(f"config for profile '{profile}' not found (looked in {candidates[0].parent})")


def absolutize_agent(value, base: Path):
    """Resolve relative prompt references against the profile they came from.

    Profile agents use paths like ``./prompts/feature-planner.md`` and
    ``{file:./prompts/personas/code-reviewer.md}``. A project config lives in a
    different directory, so the paths must be absolute or the prompts silently
    fail to load.
    """
    if isinstance(value, dict):
        return {key: absolutize_agent(item, base) for key, item in value.items()}
    if isinstance(value, list):
        return [absolutize_agent(item, base) for item in value]
    if isinstance(value, str):
        match = re.fullmatch(r"\{file:(.+)\}", value)
        if match:
            target = Path(match.group(1)).expanduser()
            if not target.is_absolute():
                target = (base / target).resolve()
            return f"{{file:{target}}}"
        if value.startswith(("./", "../")):
            return str((base / value).resolve())
    return value


def collect(profiles: list[str], home: Path) -> tuple[dict, dict, list[str], dict[str, str]]:
    servers: dict[str, dict] = {}
    agents: dict[str, dict] = {}
    owner = {"mcp": {}, "agent": {}}
    conflicts: list[str] = []
    for profile in profiles:
        config_path = resolve_profile(profile, home)
        config = load_jsonc(config_path)
        for name, server in ((config.get("mcp") or {}).get("servers") or {}).items():
            if name in servers and servers[name] != server:
                conflicts.append(f"server '{name}': {owner['mcp'][name]} -> {profile}")
            servers[name] = server
            owner["mcp"][name] = profile
        for name, agent in (config.get("agent") or {}).items():
            agent = absolutize_agent(agent, config_path.parent)
            if name in agents and agents[name] != agent:
                conflicts.append(f"agent '{name}': {owner['agent'][name]} -> {profile}")
            agents[name] = agent
            owner["agent"][name] = profile
    return dict(sorted(servers.items())), dict(sorted(agents.items())), conflicts, owner


def render(profiles: list[str], servers: dict, agents: dict) -> str:
    data: dict = {}
    if servers:
        data["mcp"] = {"servers": servers}
    if agents:
        data["agent"] = agents
    body = json.dumps({"$schema": "https://opencode.ai/config.json", **data}, ensure_ascii=False, indent=2)
    first, rest = body.split("\n", 1)
    header = [
        f"  // {MARKER} from: {', '.join(profiles)}",
        "  // Model and permissions default to the base profile; add them here to override.",
        f"  // Regenerate: oc-project-init.py --profiles {','.join(profiles)}",
    ]
    return "\n".join([first, *header, rest]) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--profiles", required=True, help="comma-separated profiles, e.g. dev,infra")
    parser.add_argument("--dir", default=".", help="project directory (default: current)")
    parser.add_argument("--config-home", default=None, help="OpenCode config home (default: $XDG_CONFIG_HOME)")
    parser.add_argument("--no-agents", action="store_true", help="only merge MCP servers")
    parser.add_argument("--check", action="store_true", help="exit 1 if the project config is out of date")
    parser.add_argument("--dry-run", action="store_true", help="print the result instead of writing")
    parser.add_argument("--force", action="store_true", help="overwrite a file not created by this tool")
    args = parser.parse_args()

    profiles = [p.strip() for p in args.profiles.split(",") if p.strip()]
    unknown = [p for p in profiles if p not in PROFILES]
    if unknown:
        parser.error(f"unknown profile(s): {', '.join(unknown)}")

    home = Path(args.config_home) if args.config_home else config_home()
    servers, agents, conflicts, _ = collect(profiles, home)
    if args.no_agents:
        agents = {}

    project = Path(args.dir)
    target = project / "opencode.jsonc"
    body = render(profiles, servers, agents)

    if args.dry_run:
        print(body, end="")
        return 0

    if args.check:
        if not target.is_file():
            print(f"{target}: missing", file=sys.stderr)
            return 1
        current = load_jsonc(target)
        expected: dict = {"$schema": "https://opencode.ai/config.json"}
        if servers:
            expected["mcp"] = {"servers": servers}
        if agents:
            expected["agent"] = agents
        if current != expected:
            print(f"{target}: out of date", file=sys.stderr)
            return 1
        print(f"{target}: up to date")
        return 0

    if target.exists() and MARKER not in target.read_text(encoding="utf-8") and not args.force:
        print(f"{target} already exists and was not generated by this tool; use --force", file=sys.stderr)
        return 1

    project.mkdir(parents=True, exist_ok=True)
    target.write_text(body, encoding="utf-8")
    print(f"wrote {target}: {len(servers)} MCP server(s), {len(agents)} agent(s)")
    for conflict in conflicts:
        print(f"  conflict {conflict}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
